import test from 'node:test';
import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
import { mkdtemp,rm } from 'node:fs/promises';
import {createServer} from '../server.mjs';

test('private upload/share/revoke/limited/password end-to-end',async t=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'repo-share-test-'));
 const server=createServer({dataDir:dir,password:'NotARealAdminPassword2026!',baseUrl:'http://127.0.0.1',cookieSecure:false,maxUpload:1024*1024});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const base=`http://127.0.0.1:${server.address().port}`;
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true})});
 const request=async(url,opts={})=>fetch(`${base}${url}`,opts);
 assert.equal((await request('/api/files')).status,401,'anonymous must not list files');
 assert.equal((await request('/files')).status,404,'directory listing never exists');
 assert.equal((await request('/private-data/metadata.json')).status,404,'metadata is not exposed');
 assert.equal((await request('/../etc/passwd')).status,404);
 assert.equal((await request('/api/upload?name=x.zip',{method:'POST',body:Buffer.from('bad')})).status,401);
 const login=await request('/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'admin',password:'NotARealAdminPassword2026!'})});
 assert.equal(login.status,200);let cookie=login.headers.get('set-cookie').split(';')[0];let {csrf}=await login.json();
 const authHeaders={'cookie':cookie,'x-csrf-token':csrf};
 const api=async(url,method='GET',body)=>request(url,{method,headers:{...authHeaders,...(body?{'content-type':'application/json'}:{})},body:body?JSON.stringify(body):undefined});
 assert.equal((await api('/api/upload?name=test.zip','POST')).status,400,'empty upload rejected');
 assert.equal((await request('/api/upload?name=test.zip',{method:'POST',headers:{cookie},body:Buffer.from('dummy')})).status,403,'CSRF protected');
 assert.equal((await request('/api/upload?name=../../secret.zip',{method:'POST',headers:authHeaders,body:Buffer.from('dummy')})).status,400,'path traversal filename rejected');
 assert.equal((await request('/api/upload?name=malware.exe',{method:'POST',headers:authHeaders,body:Buffer.from('dummy')})).status,400,'extension allowlist');
 const blob=Buffer.from('PK\x03\x04 test binary original archive');
 const up=await request('/api/upload?name=test.zip',{method:'POST',headers:authHeaders,body:blob});
 assert.equal(up.status,201);const {file}=await up.json();assert.equal(file.size,blob.length);
 const listing=await api('/api/files');assert.equal(listing.status,200);assert.equal((await listing.json()).files.length,1);
 const creation=await api('/api/shares','POST',{fileId:file.id,maxDownloads:1,ttlDays:1});assert.equal(creation.status,201);
 const {id:shareId,url}=await creation.json();const linkPath=new URL(url).pathname;
 let dl=await request(linkPath);assert.equal(dl.status,200);assert.deepEqual(Buffer.from(await dl.arrayBuffer()),blob);
 assert.equal((await request(linkPath)).status,404,'maxDownloads enforced');
 const protectedShare=await api('/api/shares','POST',{fileId:file.id,password:'let-me-in',ttlDays:0,maxDownloads:0});
 assert.equal(protectedShare.status,201);const pLink=new URL((await protectedShare.json()).url).pathname;
 const pwPage=await request(pLink);assert.equal(pwPage.status,200);assert.match(await pwPage.text(),/提取密码/);
 const denied=await request(`/api/unlock/${pLink.split('/').at(-1)}`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'wrong'})});assert.equal(denied.status,403);
 const unlocked=await request(`/api/unlock/${pLink.split('/').at(-1)}`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:'let-me-in'})});assert.equal(unlocked.status,200);
 const grant=(await unlocked.json()).url;const gr=await request(grant);assert.equal(gr.status,200);assert.deepEqual(Buffer.from(await gr.arrayBuffer()),blob);
 assert.equal((await request(grant)).status,404,'grant single use');
 assert.equal((await api(`/api/shares/${shareId}`,'DELETE')).status,200);
 assert.equal((await api(`/api/files/${file.id}`,'DELETE')).status,200);
 assert.equal((await request(pLink)).status,404,'file deletion revokes shares');
});

test('metadata persists across restart and expired shares cannot download', async t=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'repo-share-persist-'));
 t.after(async()=>rm(dir,{recursive:true,force:true}));
 const opt={dataDir:dir,password:'AnotherStrongAdminPassword2026!',baseUrl:'https://repo.ailp.fun',cookieSecure:false};
 const start=async()=>{const server=createServer(opt);await new Promise(ok=>server.listen(0,'127.0.0.1',ok));return {server,base:`http://127.0.0.1:${server.address().port}`}};
 let {server,base}=await start();
 let login=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'admin',password:opt.password})});
 let cookie=login.headers.get('set-cookie').split(';')[0];let csrf=(await login.json()).csrf;
 const hdr={cookie,'x-csrf-token':csrf};
 let uploaded=await fetch(base+'/api/upload?name=persist.7z',{method:'POST',headers:hdr,body:Buffer.from('7zip content')});assert.equal(uploaded.status,201);let {file}=await uploaded.json();
 let shared=await fetch(base+'/api/shares',{method:'POST',headers:{...hdr,'content-type':'application/json'},body:JSON.stringify({fileId:file.id,ttlDays:1})});let shareUrl=(await shared.json()).url;
 await new Promise(ok=>server.close(ok));
 ({server,base}=await start());
 assert.equal((await fetch(base+'/api/files')).status,401,'sessions must not survive restart');
 let dl=await fetch(base+new URL(shareUrl).pathname);assert.equal(dl.status,200);assert.equal(await dl.text(),'7zip content');
 // Legacy share state can expire between requests; force expiration and verify it is never served after restart.
 await new Promise(ok=>server.close(ok));
 let metadataPath=path.join(dir,'metadata.json');let fs=await import('node:fs/promises');let meta=JSON.parse(await fs.readFile(metadataPath,'utf8'));meta.shares[0].expiresAt=Date.now()-1000;await fs.writeFile(metadataPath,JSON.stringify(meta));
 ({server,base}=await start());
 assert.equal((await fetch(base+new URL(shareUrl).pathname)).status,404);
 await new Promise(ok=>server.close(ok));
});
