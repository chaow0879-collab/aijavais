'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const H = require('./helpers');
const SEC = require('../lib/security');
const { ToolRegistry } = require('../lib/tools-v2');
const startHttpFixture = require('./fixtures/mcp-http-server.cjs');

test('MCP HTTP: initialize/session/list/call over JSON and SSE, bearer auth, disable and URL policy (local protocol fixture)', async t => {
  const fx = await startHttpFixture();
  t.after(() => fx.server.close());
  const policy = SEC.policyFromEnv({ LOCAL_MODEL_TARGETS: '127.0.0.1:' + fx.port });
  const reg = new ToolRegistry({ mcpServers: [], httpServers: [{ id: 'remote', url: `http://127.0.0.1:${fx.port}/mcp` }], policy, tokenFor: () => 'fixture-token' });
  t.after(() => reg.close());
  const d = await reg.discover();
  assert.deepEqual(d.servers, [{ serverId: 'remote', available: true, tools: 2 }]);
  assert.equal((await reg.call('mcp:remote:echo', { value: 'a' }, { allowedTools: ['mcp:remote:echo'] })).content[0].text, 'json:a');
  const sse = await reg.call('mcp:remote:sse_echo', { value: 'b' }, { allowedTools: ['mcp:remote:sse_echo'] });
  assert.equal(sse.content[0].text, 'sse:b'); assert.equal(sse.executionMode, 'mcp');
  await assert.rejects(reg.call('mcp:remote:echo', { value: 'a' }, { allowedTools: [] }), e => e.code === 'tool_forbidden');
  assert.ok(fx.seen.filter(x => x.method !== 'initialize').every(x => x.session === 'sess-1' && x.version === '2025-06-18'), 'session id and protocol version are echoed');
  assert.equal(reg.logs.filter(l => l.action === 'call' && l.status === 'done').length, 2);
  reg.setEnabled('remote', false);
  await assert.rejects(reg.call('mcp:remote:echo', { value: 'a' }, { allowedTools: ['mcp:remote:echo'] }), e => e.code === 'tool_missing' || e.code === 'tool_disabled');
  assert.equal((await reg.discover()).servers[0].code, 'disabled');
  const bad = new ToolRegistry({ mcpServers: [], httpServers: [{ id: 'remote', url: `http://127.0.0.1:${fx.port}/mcp` }], policy, tokenFor: () => 'wrong' });
  assert.equal((await bad.discover()).servers[0].code, 'mcp_auth');
  assert.throws(() => reg.addHttpServer({ id: 'plain', url: 'http://mcp.example.com/mcp' }), /https/);
  assert.throws(() => reg.addHttpServer({ id: 'q', url: 'https://mcp.example.com/mcp?token=x' }), /查询参数/);
  assert.throws(() => reg.addHttpServer({ id: 'bad id!', url: 'https://mcp.example.com/mcp' }), e => e.code === 'invalid_mcp_config');
  const priv = new ToolRegistry({ mcpServers: [], httpServers: [{ id: 'lan', url: 'https://10.0.0.5/mcp' }], policy: SEC.policyFromEnv({}) });
  assert.equal((await priv.discover()).servers[0].code, 'mcp_unreachable', 'private address blocked by the outbound policy');
});

test('V2 HTTP: MCP management center — catalog, add remote, test, call, logs, disable, restart persistence, remove (local fixtures)', async t => {
  const fx = await startHttpFixture('ui-token');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'aij-mcp-cfg-'));
  const cfg = path.join(dir, 'mcp.json');
  fs.writeFileSync(cfg, JSON.stringify({ servers: [{ id: 'local', command: process.execPath, args: [path.join(__dirname, 'fixtures', 'mcp-v2-server.cjs')] }] }));
  const env = { LOCAL_MODEL_TARGETS: '127.0.0.1:' + fx.port, AIJ_MCP_SERVERS_FILE: cfg };
  let S = await H.boot({ env });
  t.after(async () => { await S.stop(); fx.server.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  assert.equal((await S.call('GET', '/api/v2/mcp', undefined, { cookie: false })).status, 401);
  const view = await S.call('GET', '/api/v2/mcp');
  assert.ok(view.json.catalog.some(c => c.id === 'time' && c.transport === 'stdio'));
  assert.ok(view.json.catalog.every(c => c.transport === 'http' || /管理员/.test(c.install)), 'stdio entries are installed by the server administrator, never by the web UI');
  assert.deepEqual(view.json.servers.map(s => [s.serverId, s.transport, s.removable]), [['local', 'stdio', false]]);
  assert.doesNotMatch(view.text, /mcp-v2-server\.cjs/, 'stdio arguments are never listed');
  const add = await S.call('POST', '/api/v2/mcp/servers', { id: 'remote', name: '远程测试', url: `http://127.0.0.1:${fx.port}/mcp`, token: 'ui-token' });
  assert.equal(add.status, 201, add.text); assert.equal(add.json.server.hasToken, true);
  assert.doesNotMatch((await S.call('GET', '/api/v2/mcp')).text, /ui-token/, 'token never returned');
  assert.equal((await S.call('POST', '/api/v2/mcp/servers', { id: 'remote', url: `http://127.0.0.1:${fx.port}/mcp` })).status, 400, 'duplicate id rejected');
  const tested = await S.call('POST', '/api/v2/mcp/servers/remote/test', {});
  assert.equal(tested.json.state.available, true); assert.deepEqual(tested.json.tools.map(x => x.toolId).sort(), ['mcp:remote:echo', 'mcp:remote:sse_echo']);
  const local = await S.call('POST', '/api/v2/mcp/servers/local/test', {});
  assert.equal(local.json.state.available, true);
  // External tools: a browser-supplied grant is not enough; the server issues a single-use confirmation bound to tool + args.
  const unconfirmed = await S.call('POST', '/api/v2/tools/call', { toolId: 'mcp:remote:sse_echo', args: { value: 'hi' }, allowedTools: ['mcp:remote:sse_echo'] });
  assert.equal(unconfirmed.status, 428); assert.equal(unconfirmed.json.risk, 'external');
  const prep = await S.call('POST', '/api/v2/tools/call/prepare', { toolId: 'mcp:remote:sse_echo', args: { value: 'hi' } });
  assert.equal(prep.json.risk, 'external'); assert.match(prep.json.warnings.join(''), /费用/);
  assert.equal((await S.call('POST', '/api/v2/tools/call', { toolId: 'mcp:remote:sse_echo', args: { value: 'other' }, confirmationId: prep.json.confirmationId })).status, 428, 'confirmation bound to the exact arguments');
  const prep2 = await S.call('POST', '/api/v2/tools/call/prepare', { toolId: 'mcp:remote:sse_echo', args: { value: 'hi' } });
  const call = await S.call('POST', '/api/v2/tools/call', { toolId: 'mcp:remote:sse_echo', args: { value: 'hi' }, confirmationId: prep2.json.confirmationId });
  assert.equal((await S.call('POST', '/api/v2/tools/call', { toolId: 'mcp:remote:sse_echo', args: { value: 'hi' }, confirmationId: prep2.json.confirmationId })).status, 428, 'single use');
  assert.equal(call.json.result.content[0].text, 'sse:hi');
  assert.ok((await S.call('GET', '/api/v2/mcp')).json.logs.some(l => l.serverId === 'remote' && l.action === 'call' && l.status === 'done'));
  assert.equal((await S.call('POST', '/api/v2/mcp/servers/remote/disable', {})).status, 200);
  assert.equal((await S.call('POST', '/api/v2/mcp/servers/remote/test', {})).json.state.code, 'disabled');
  const caps = await S.call('GET', '/api/v2/capabilities');
  assert.ok(!caps.json.capabilities.some(c => c.id === 'mcp:remote:echo'), 'disabled server tools disappear from the capability list');
  // Restart: remote server, its token and disabled state persist.
  const dataDir = S.dir; await S.kill(); S = await H.boot({ env, dir: dataDir });
  const after = (await S.call('GET', '/api/v2/mcp')).json.servers.find(s => s.serverId === 'remote');
  assert.equal(after.enabled, false); assert.equal(after.hasToken, true);
  await S.call('POST', '/api/v2/mcp/servers/remote/enable', {});
  assert.equal((await S.call('POST', '/api/v2/mcp/servers/remote/test', {})).json.state.available, true, 'token survived restart');
  assert.equal((await S.call('DELETE', '/api/v2/mcp/servers/local')).status, 400, 'file-managed stdio server cannot be deleted from the web');
  assert.equal((await S.call('DELETE', '/api/v2/mcp/servers/remote')).status, 200);
  assert.deepEqual((await S.call('GET', '/api/v2/mcp')).json.servers.map(s => s.serverId), ['local']);
});
